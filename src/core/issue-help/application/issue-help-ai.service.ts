import { OpenRouterAiService } from '../../ai/application/openrouter-ai.service';
import { formatCompactIssueContextPackForLlm, IssueHelpContextPack, IssueHelpIntent } from './issue-context-pack.builder';

function buildIntentInstruction(intent: IssueHelpIntent): string {
  switch (intent) {
    case 'summary':
      return 'Сделай содержательное саммари задачи: цель, текущее состояние, что уже произошло, что остается сделать и где риск.';
    case 'why-stuck':
      return 'Объясни, почему задача не двигается: что именно ее тормозит, какого ответа или действия ждут и от кого именно, если это видно из контекста.';
    case 'next-step':
      return 'Подскажи, какой следующий шаг выглядит самым логичным, на ком он находится и что именно нужно сделать.';
    case 'what-happened':
      return 'Кратко и конкретно опиши, что уже произошло по задаче: ключевые изменения, коммуникации, решения и текущую точку.';
    default:
      return 'Помоги разобраться с задачей: что по ней видно, где риск, чего ждут и что делать дальше.';
  }
}

function buildSystemPrompt(): string {
  return [
    'Ты помощник по Yandex Tracker.',
    'Отвечай по-русски, конкретно, без воды и без выдумывания фактов.',
    'Используй только предоставленный контекст задачи.',
    'Если данных недостаточно, прямо скажи, чего именно не хватает.',
    'Не ограничивайся общими фразами вроде "нужно уточнить", если в контексте есть конкретный участник, конкретный вопрос или конкретный блокер.',
    'Если задача ждет ответа, обязательно укажи: от кого ждут ответ и по какому вопросу или теме это видно из comments/evidence/highlights/derived_context. Если тема вопроса не видна, так и напиши явно.',
    'Определяй владельца следующего шага по смыслу и хронологии комментариев, а не по служебным полям Tracker.',
    'Если самый свежий комментарий содержит обещание автора выполнить действие (например, «сейчас запрошу», «уточню», «сообщу»), следующий шаг находится у этого автора, даже если предыдущий комментарий был вопросом другого участника.',
    'Если derived_context показывает, что автор последнего комментария сам ждет внешнюю реакцию, не назначай следующий шаг автоматически на автора.',
    'Не пересказывай весь контекст: выбери только самые важные факты и не дублируй одно и то же разными словами.',
    'Если в комментариях есть формулировки вроде "буду ждать ОС", "осталось согласовать правки", "требуется доработка", используй их как ключевую причину ожидания и сформулируй человеческим языком, чего именно ждут.',
    'Всегда добавляй 1-2 предложения общего смысла задачи, чтобы читателю было понятно, что это за задача и зачем она делается, а не только локальная причина блокировки.',
    'Если упоминаешь техническую деталь вроде вебхука, SLA, статуса или бота, поясняй в одном предложении, какую роль эта деталь играет в задаче.',
    'Если делаешь саммари, убирай второстепенные детали и оставляй только то, что важно для быстрого понимания состояния задачи.',
    'Отвечай максимум в 3 коротких блоках:',
    '1. Коротко — прямой ответ в 1-2 предложениях.',
    '2. Почему / чего ждут — не более 3 конкретных пунктов.',
    '3. Что делать — не более 2 конкретных пунктов.',
    'Не добавляй отдельные блоки с метаданными и полным перечнем фактов.',
    'Не повторяй один факт в разных формулировках.',
    'Весь ответ должен быть не длиннее 1000 символов.'
  ].join('\n');
}

function buildUserPrompt(pack: IssueHelpContextPack): string {
  return [
    buildIntentInstruction(pack.intent),
    '',
    `Запрос пользователя: ${pack.userRequest}`,
    '',
    'Особые требования к ответу:',
    '- не повторяй весь контекст подряд;',
    '- делай выводы только из фактов;',
    '- сначала учитывай самый свежий содержательный комментарий и хронологию диалога, затем DERIVED_CONTEXT и EVIDENCE;',
    '- если видно ожидание ответа, явно напиши, кого ждут и что именно, если это считывается из контекста;',
    '- поля waitingSubject / waitingQuestion описывают тему разговора, но не доказывают, кто владеет следующим шагом; владельца определяй по последнему обещанному действию;',
    '- не отвечай только локальной технической причиной без общего смысла задачи; сначала дай контекст, потом блокер;',
    '- если точная формулировка вопроса не видна, честно укажи это;',
    '- если есть несколько возможных причин торможения, ранжируй их по вероятности;',
    '',
    'Контекст задачи ниже.',
    formatCompactIssueContextPackForLlm(pack)
  ].join('\n');
}

export class IssueHelpAiService {
  constructor(private readonly openRouterAiService: OpenRouterAiService) {}

  isEnabled(): boolean {
    return this.openRouterAiService.isEnabled();
  }

  async generateAnswer(pack: IssueHelpContextPack): Promise<string> {
    return this.openRouterAiService.generateText({
      system: buildSystemPrompt(),
      temperature: 0.2,
      messages: [
        {
          role: 'user',
          text: buildUserPrompt(pack)
        }
      ]
    });
  }
}
